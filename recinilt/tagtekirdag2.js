function showTab(day) {
    // Tüm sekmeleri gizle
    const tabs = document.querySelectorAll('.tab');
    const contents = document.querySelectorAll('.tab-content');
    
    tabs.forEach(tab => tab.classList.remove('active'));
    contents.forEach(content => content.classList.remove('active'));
    
    // Seçilen sekmeyi göster
    event.target.classList.add('active');
    document.getElementById(day).classList.add('active');
    
    // Tablo verilerini doldur
    fillTable(day);
}

function fillTable(day) {
    const tableBody = document.getElementById(day + '-table');
    if (!tableBody) return;
    
    let html = '';
    const dayData = hourlyData[day];
    
    if (dayData) {
        dayData.forEach(([time, regions]) => {
            html += `<tr><td class="time-column">${time}</td>`;
            regions.forEach(cellData => {
                const [icon, risk] = cellData.split('/');
                const cellClass = getCellClass(icon);
                html += `<td class="${cellClass}">
                    <div class="cell-content">
                        <span class="demand-icon">${icon}</span>
                        <span class="police-risk risk-${risk}">${risk}</span>
                    </div>
                </td>`;
            });
            html += '</tr>';
        });
    }
    
    tableBody.innerHTML = html;
}

